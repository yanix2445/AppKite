import AppKit

@MainActor
final class PasteboardClient: ClipboardCollectionSource {
    struct ForegroundApplication: Equatable {
        let processIdentifier: pid_t
        let bundleIdentifier: String
    }

    enum WriteResult {
        case written(Int)
        case changed
        case failed
    }

    private static let concealedTypes: Set<NSPasteboard.PasteboardType> = [
        .init("org.nspasteboard.ConcealedType"),
        .init("com.agilebits.onepassword"),
    ]
    private static let declaredSource = NSPasteboard.PasteboardType("org.nspasteboard.source")
    private static let remoteClipboard = NSPasteboard.PasteboardType(
        "com.apple.is-remote-clipboard")
    private static let untrackedSourceTypes: Set<NSPasteboard.PasteboardType> = [
        .init("org.nspasteboard.TransientType"),
        .init("org.nspasteboard.AutoGeneratedType"),
    ]
    private static let filePromiseTypes = Set(
        NSFilePromiseReceiver.readableDraggedTypes.map { NSPasteboard.PasteboardType($0) }
    )
    private enum FileSelectionError: Error {
        case invalidURL
    }

    private let pasteboard: NSPasteboard
    private let readAccessBehavior: () -> NSPasteboard.AccessBehavior
    private let foregroundApplication: () -> ForegroundApplication?
    private var lastForegroundApplication: ForegroundApplication?
    private var lastChangeCount: Int
    private var lastAccessBehavior: NSPasteboard.AccessBehavior
    private var lastReadStatus = ClipboardReadStatus.available

    init(
        pasteboard: NSPasteboard = .general,
        readAccessBehavior: (() -> NSPasteboard.AccessBehavior)? = nil,
        foregroundApplication: (() -> ForegroundApplication?)? = nil
    ) {
        self.pasteboard = pasteboard
        let accessBehavior = readAccessBehavior ?? { pasteboard.accessBehavior }
        self.readAccessBehavior = accessBehavior
        self.foregroundApplication =
            foregroundApplication ?? {
                guard pasteboard.name == .general,
                    let app = NSWorkspace.shared.frontmostApplication,
                    let identifier = app.bundleIdentifier
                else { return nil }
                return ForegroundApplication(
                    processIdentifier: app.processIdentifier, bundleIdentifier: identifier)
            }
        lastChangeCount = pasteboard.changeCount
        lastAccessBehavior = accessBehavior()
    }

    var changeCount: Int { pasteboard.changeCount }
    var invalidFileSelectionChangeCount: Int? {
        lastReadStatus == .invalidFileSelection ? lastChangeCount : nil
    }

    var readStatus: ClipboardReadStatus {
        if readAccessBehavior() == .alwaysDeny { return .denied }
        return lastReadStatus == .denied ? .available : lastReadStatus
    }

    func ignoreCurrentContents() {
        lastChangeCount = pasteboard.changeCount
        lastAccessBehavior = readAccessBehavior()
        lastReadStatus = .available
        lastForegroundApplication = nil
    }

    func poll(
        ignoringConfidentialCopies: Bool = true,
        isSourceExcluded: (String) -> Bool = { _ in false }
    ) -> (text: String, sourceBundleIdentifier: String?)? {
        guard
            let copy = pollPayload(
                ignoringConfidentialCopies: ignoringConfidentialCopies,
                isSourceExcluded: isSourceExcluded
            ),
            let text = copy.payload.items.lazy.flatMap(\.representations)
                .first(where: { $0.type == ClipboardPayload.utf8TextType })
                .flatMap({ String(data: $0.data, encoding: .utf8) }), !text.isEmpty
        else { return nil }
        return (text, copy.sourceBundleIdentifier)
    }

    func pollPayload(
        ignoringConfidentialCopies: Bool = true,
        isSourceExcluded: (String) -> Bool = { _ in false }
    ) -> ClipboardCopy? {
        let changeCount = pasteboard.changeCount
        let previousApplication = lastForegroundApplication
        let currentApplication = foregroundApplication()
        lastForegroundApplication = currentApplication
        let accessBehavior = readAccessBehavior()
        let wasDenied = lastAccessBehavior == .alwaysDeny
        lastAccessBehavior = accessBehavior

        if accessBehavior == .alwaysDeny || wasDenied {
            lastChangeCount = changeCount
            lastReadStatus = .available
            lastForegroundApplication = nil
            return nil
        }

        guard changeCount != lastChangeCount else { return nil }
        lastChangeCount = changeCount
        lastReadStatus = .available

        guard let items = pasteboard.pasteboardItems else {
            noteReadFailure(changeCount: changeCount)
            return nil
        }

        guard canContinueReading(changeCount: changeCount),
            !ignoringConfidentialCopies
                || items.allSatisfy({ Self.concealedTypes.isDisjoint(with: $0.types) })
        else { return nil }

        let isRemote = items.contains { $0.types.contains(Self.remoteClipboard) }
        let sources = Set(
            items.compactMap {
                bundleIdentifier(from: $0.string(forType: Self.declaredSource))
            })
        if sources.contains(where: isSourceExcluded) { return nil }
        let source = !isRemote && sources.count == 1 ? sources.first : nil
        guard canContinueReading(changeCount: changeCount) else { return nil }

        var payloadItems: [ClipboardPayload.Item] = []
        for item in items {
            guard canContinueReading(changeCount: changeCount) else { return nil }
            let fileURL: URL?
            do {
                fileURL = try self.fileURL(in: item)
            } catch {
                noteReadFailure(.invalidFileSelection, changeCount: changeCount)
                return nil
            }
            var representations: [ClipboardPayload.Representation] = []
            var didFailToRead = false
            for type in item.types where ClipboardFormatCodec.supports(type.rawValue) {
                // File URLs are replaced with archive URLs during replay. Preserve no stale alias.
                if fileURL != nil, type == .URL { continue }
                if fileURL != nil, ClipboardMediaPreview.supportsRepresentation(type.rawValue) {
                    continue
                }
                guard let data = item.data(forType: type) else {
                    didFailToRead = true
                    continue
                }
                guard type != .string || !data.isEmpty else { continue }
                if let fileURL, ClipboardFormatCodec.isTextType(type.rawValue),
                    Self.isOriginalPath(data, fileURL: fileURL)
                {
                    continue
                }
                representations.append(.init(type: type.rawValue, data: data))
            }
            if fileURL == nil, representations.isEmpty {
                if didFailToRead {
                    noteReadFailure(changeCount: changeCount)
                    return nil
                }
                continue
            }
            payloadItems.append(
                .init(
                    representations: ClipboardFormatCodec.withTabularFallback(representations),
                    fileURL: fileURL
                ))
        }

        guard !payloadItems.isEmpty else { return nil }
        let probableSource: String?
        if !isRemote,
            !items.contains(where: {
                $0.types.contains(Self.declaredSource)
                    || !Self.untrackedSourceTypes.isDisjoint(with: $0.types)
            }),
            let currentApplication,
            currentApplication == previousApplication,
            currentApplication == foregroundApplication(),
            currentApplication.processIdentifier != ProcessInfo.processInfo.processIdentifier
        {
            probableSource = currentApplication.bundleIdentifier
        } else {
            probableSource = nil
        }
        guard canContinueReading(changeCount: changeCount) else { return nil }
        return ClipboardCopy(
            payload: ClipboardPayload(items: payloadItems),
            sourceBundleIdentifier: source, probableSourceBundleIdentifier: probableSource,
            isRemote: isRemote)
    }

    func write(_ text: String, replacing expectedChangeCount: Int) -> WriteResult {
        write(.plainText(text), replacing: expectedChangeCount)
    }

    func write(_ payload: ClipboardPayload, replacing expectedChangeCount: Int) -> WriteResult {
        guard !payload.items.isEmpty else { return .failed }
        var items: [NSPasteboardItem] = []
        for payloadItem in payload.items {
            let item = NSPasteboardItem()
            if let fileURL = payloadItem.fileURL,
                !item.setString(fileURL.absoluteString, forType: .fileURL)
            {
                return .failed
            }
            let representations = ClipboardFormatCodec.replayRepresentations(
                payloadItem.representations)
            for representation in representations {
                guard ClipboardFormatCodec.supports(representation.type),
                    item.setData(representation.data, forType: .init(representation.type))
                else { return .failed }
            }
            guard !item.types.isEmpty else { return .failed }
            items.append(item)
        }
        guard isCurrent(changeCount: expectedChangeCount) else { return .changed }

        let changeCount = pasteboard.clearContents()
        lastChangeCount = changeCount
        guard isCurrent(changeCount: changeCount) else { return .changed }
        let written = pasteboard.writeObjects(items)
        guard isCurrent(changeCount: changeCount) else { return .changed }
        return written ? .written(changeCount) : .failed
    }

    func isCurrent(changeCount: Int) -> Bool {
        pasteboard.changeCount == changeCount
    }

    private func noteReadFailure(_ status: ClipboardReadStatus = .failed, changeCount: Int) {
        // AppKit's synchronous reads report failure as nil, with no per-read permission status.
        if canContinueReading(changeCount: changeCount) {
            lastReadStatus = status
        }
    }

    private func canContinueReading(changeCount: Int) -> Bool {
        if readAccessBehavior() == .alwaysDeny {
            lastAccessBehavior = .alwaysDeny
            lastForegroundApplication = nil
            lastReadStatus = .denied
            return false
        }
        return isCurrent(changeCount: changeCount)
    }

    private func fileURL(in item: NSPasteboardItem) throws -> URL? {
        let hasFileURL = item.types.contains(.fileURL)
        let type: NSPasteboard.PasteboardType = hasFileURL ? .fileURL : .URL
        let value = item.types.contains(type) ? item.string(forType: type) : nil
        let hasFileScheme = value?.lowercased().hasPrefix("file:") == true
        guard hasFileURL || hasFileScheme else {
            if !Self.filePromiseTypes.isDisjoint(with: item.types) {
                throw FileSelectionError.invalidURL
            }
            return nil
        }
        guard let value, let url = URL(string: value),
            url.isFileURL, url.path.hasPrefix("/"),
            url.host == nil || url.host == "" || url.host == "localhost"
        else { throw FileSelectionError.invalidURL }
        return url
    }

    private static func isOriginalPath(_ data: Data, fileURL: URL) -> Bool {
        let path = fileURL.path
        let urlString = fileURL.absoluteString
        guard data.count <= 4 * max(path.utf8.count, urlString.utf8.count) + 2 else { return false }
        for encoding: String.Encoding in [.utf8, .utf16, .utf16LittleEndian, .utf16BigEndian] {
            if let value = String(data: data, encoding: encoding),
                value == path || value == urlString
            {
                return true
            }
        }
        return false
    }

    private func bundleIdentifier(from declaredSource: String?) -> String? {
        // A producer may declare its source. The foreground app is not evidence of ownership.
        guard let declaredSource,
            declaredSource.utf8.allSatisfy(Self.isBundleIdentifierByte)
        else {
            return nil
        }
        let components = declaredSource.split(separator: ".", omittingEmptySubsequences: false)
        guard components.count > 1, components.allSatisfy({ !$0.isEmpty }) else { return nil }
        return declaredSource
    }

    private static func isBundleIdentifierByte(_ byte: UInt8) -> Bool {
        switch byte {
        case 45, 46, 48...57, 65...90, 97...122:
            true
        default:
            false
        }
    }
}
